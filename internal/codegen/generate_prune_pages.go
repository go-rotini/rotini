package codegen

import (
	"fmt"
	"path"
	"path/filepath"
	"strconv"
	"strings"
)

// The previous generate's cmd file records which pages it wrote: the files its feature vars
// embed and the man pages ManPages lists. A page it wrote that this run doesn't produce, such
// as the old root's man pages after a rename or a page left in an old embed_dir, is removed on
// that record, without guessing from file names alone.

// generatedLine is the line every generated Go file carries; a cmd file without it isn't
// rotini's, and records nothing.
const generatedLine = "// Code generated by rotini; DO NOT EDIT."

// priorPages is what the previous generate wrote for the doc features.
type priorPages struct {
	embedded   []string // absolute paths of the page files the cmd file embedded
	manPages   []string // the man page names ManPages listed
	manSection string   // ManSection, "" when the man feature was off
	root       string   // the root command's name, which names the installed completion scripts
}

// readPriorPages reads the pages the previous generate wrote from the cmd file it left. It runs
// before the cmd file is rewritten. A missing or hand-written file records nothing.
func (p *program) readPriorPages() error {
	src, _, exists, err := p.plan.read(filepath.Join(p.layout.cmdDir, p.layout.cmdFile))
	if err != nil || !exists {
		return err
	}
	p.prior = parsePriorPages(string(src), p.layout.cmdDir)
	return nil
}

// parsePriorPages extracts the page record from a generated cmd file in cmdDir. An embedded
// file counts only when its var is a doc feature's and its name is shaped like that feature's
// pages, and only when it resolves inside cmdDir.
func parsePriorPages(src, cmdDir string) priorPages {
	var pp priorPages
	lines := strings.Split(src, "\n")
	if !containsLine(lines, generatedLine) {
		return pp
	}
	inManPages := false
	for i, line := range lines {
		next := ""
		if i+1 < len(lines) {
			next = lines[i+1]
		}
		switch {
		case strings.HasPrefix(line, "//go:embed "):
			if abs, ok := embeddedPage(line, next, cmdDir); ok {
				pp.embedded = append(pp.embedded, abs)
			}
		case strings.HasPrefix(line, "const ManSection = "):
			if s, err := strconv.Unquote(strings.TrimPrefix(line, "const ManSection = ")); err == nil && len(s) == 1 && s[0] >= '1' && s[0] <= '9' {
				pp.manSection = s
			}
		case line == "var definition = "+rotiniPkgName+".Definition{":
			if rest, ok := strings.CutPrefix(strings.TrimSpace(next), "Name:"); ok {
				pp.root = quotedName(strings.TrimSuffix(strings.TrimSpace(rest), ","))
			}
		case strings.HasPrefix(line, "func ManPages() "):
			inManPages = true
		case inManPages && line == "}":
			inManPages = false
		case inManPages:
			if name := manPagesEntry(line); name != "" {
				pp.manPages = append(pp.manPages, name)
			}
		}
	}
	if pp.manSection == "" {
		pp.manPages = nil
	}
	return pp
}

// embeddedPage returns the absolute path a //go:embed line names when the var declared on the
// next line is a doc feature's, the file is shaped like that feature's pages, and it resolves
// inside cmdDir.
func embeddedPage(line, next, cmdDir string) (string, bool) {
	rel := strings.TrimSpace(strings.TrimPrefix(line, "//go:embed "))
	feat, ok := pageFeatureOfVar(next)
	if !ok || !feat.namesPage(path.Base(rel)) {
		return "", false
	}
	abs := filepath.Join(cmdDir, filepath.FromSlash(rel))
	if r, err := filepath.Rel(cmdDir, abs); err != nil || r == ".." || strings.HasPrefix(r, ".."+string(filepath.Separator)) {
		return "", false
	}
	return abs, true
}

// manPagesEntry returns the page name of one ManPages entry ({Name: "taskr-add", ...}), or "".
func manPagesEntry(line string) string {
	rest, ok := strings.CutPrefix(strings.TrimSpace(line), "{Name: ")
	if !ok {
		return ""
	}
	end := strings.Index(rest, `", `)
	if end < 0 {
		return ""
	}
	return quotedName(rest[:end+1])
}

// quotedName unquotes a Go string literal naming a page or command, or returns "" when it
// isn't one or the name could reach outside a directory.
func quotedName(lit string) string {
	name, err := strconv.Unquote(lit)
	if err != nil || !safePageName(name) {
		return ""
	}
	return name
}

// safePageName reports whether name can name a file in a directory without leaving it.
func safePageName(name string) bool {
	return name != "" && name != "." && name != ".." && !strings.ContainsAny(name, `/\`)
}

// containsLine reports whether want is one of lines, ignoring trailing whitespace.
func containsLine(lines []string, want string) bool {
	for _, l := range lines {
		if strings.TrimRight(l, " \t\r") == want {
			return true
		}
	}
	return false
}

// pageFeatureOfVar returns the doc feature whose page var line declares (`var HelpRoot string`).
func pageFeatureOfVar(line string) (docFeature, bool) {
	name, ok := strings.CutPrefix(line, "var ")
	if !ok {
		return docFeature{}, false
	}
	name, ok = strings.CutSuffix(strings.TrimSpace(name), " string")
	if !ok {
		return docFeature{}, false
	}
	for _, d := range []docFeature{helpFeatureDesc, manFeatureDesc, markdownFeatureDesc, completionFeatureDesc} {
		if strings.HasPrefix(name, d.varPrefix) {
			return d, true
		}
	}
	return docFeature{}, false
}

// pruneUnproducedPages removes each page file the previous generate embedded that no
// embed-mode feature writes now. Keep-listed paths are preserved.
// Paths compare case-insensitively, so a case-only rename never removes the page just written
// on a file system that ignores case.
func pruneUnproducedPages(pl *planner, lay layout, keepList []string, outputs []featureOutput, embedded []string) error {
	current := map[string]bool{}
	for _, o := range outputs {
		if !o.embed {
			continue
		}
		for _, n := range o.nodes {
			current[strings.ToLower(filepath.Join(o.absEmbedDir, n.file))] = true
		}
	}
	keep := make(map[string]bool, len(keepList))
	for _, k := range keepList {
		keep[filepath.ToSlash(k)] = true
	}
	for _, path := range embedded {
		if current[strings.ToLower(path)] {
			continue
		}
		if r, err := filepath.Rel(lay.cmdDir, path); err == nil && keep[filepath.ToSlash(r)] {
			continue
		}
		if err := pl.remove(path); err != nil {
			return fmt.Errorf("prune %s: %w", filepath.ToSlash(path), err)
		}
	}
	return nil
}
