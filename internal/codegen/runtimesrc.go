package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"io/fs"
	"sort"
	"strings"

	rotini "github.com/go-rotini/rotini/internal/runtime"
)

// mergeRuntime combines the ENTIRE rotini runtime into a single Go source file under
// package pkgName: every non-test runtime file's declarations concatenated, their
// third-party imports unioned, under one package clause. The runtime files reference
// each other unqualified (same package) and carry their own imports, so the merged
// result is a self-contained package the generated framework imports — written to the
// conf's one runtime 'file' (see writeEmittedRuntime). This is what makes a "single
// file" request actually produce a single file instead of a package copy.
func mergeRuntime(pkgName string) ([]byte, error) {
	src, err := runtimeSourceFiles()
	if err != nil {
		return nil, err
	}

	// Merge in a stable filename order so the output is deterministic across passes.
	names := make([]string, 0, len(src))
	for name := range src {
		names = append(names, name)
	}
	sort.Strings(names)

	seen := map[string]bool{}
	var imports []string
	var bodies [][]byte
	for _, name := range names {
		imps, body, err := splitGoFile(src[name])
		if err != nil {
			return nil, fmt.Errorf("merge runtime %s: %w", name, err)
		}
		for _, imp := range imps {
			if !seen[imp] { // dedup by exact spec — the runtime aliases each path consistently
				seen[imp] = true
				imports = append(imports, imp)
			}
		}
		if len(bytes.TrimSpace(body)) > 0 {
			bodies = append(bodies, body)
		}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by rotini; DO NOT EDIT.\n")
	buf.WriteString("package " + pkgName + "\n\n")
	if len(imports) > 0 {
		buf.WriteString("import (\n")
		for _, imp := range imports {
			buf.WriteString("\t" + imp + "\n")
		}
		buf.WriteString(")\n\n")
	}
	for i, body := range bodies {
		if i > 0 {
			buf.WriteString("\n")
		}
		buf.Write(body)
		buf.WriteString("\n")
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("merge runtime: gofmt: %w\n--- merged source ---\n%s", err, buf.String())
	}
	return groupImports(formatted)
}

// runtimeSourceFiles returns the emittable runtime source: every runtime .go file
// (from the internal/runtime package's own embedded [rotini.Source]), keyed by base
// filename, bytes verbatim. The runtime's test files and its embed.go (the self-embed
// support file) are excluded: neither is runtime behavior, so neither is merged into
// user projects.
func runtimeSourceFiles() (map[string][]byte, error) {
	out := map[string][]byte{}
	entries, err := rotini.Source.ReadDir(".")
	if err != nil {
		return nil, err
	}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || strings.HasSuffix(name, "_test.go") || name == "embed.go" {
			continue
		}
		b, err := fs.ReadFile(rotini.Source, name)
		if err != nil {
			return nil, err
		}
		out[name] = b
	}
	return out, nil
}
