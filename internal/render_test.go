func TestRender_rotiniGen_ancestorComposition(t *testing.T) {
	t.Parallel()
	in := internal.NewRenderInput("rotini", fixtureSpec())
	out := renderOK(t, "rotini.gen.tmpl", in)
	// FooBarInputs.PopulateFromArgv must pull from root scope (""),
	// the "foo" intermediate scope, and the "bar" leaf scope.
	got := string(out)
	for _, want := range []string{
		`if scope := r.FlagsByScope[""]; scope != nil {`,
		`if scope := r.FlagsByScope["foo"]; scope != nil {`,
		`if scope := r.FlagsByScope["bar"]; scope != nil {`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("ancestor composition missing %q", want)
		}
	}
}

