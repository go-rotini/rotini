// =============================================================================
// Determinism — multiple renders produce identical output
// =============================================================================

// TestRender_deterministicOrdering verifies the framework template
// renders to byte-identical output across runs. Map iteration order
// in Go is randomized; sortedness of every iteration site is a hard
// requirement for byte-stable regen.
func TestRender_deterministicOrdering(t *testing.T) {
	t.Parallel()
	in := internal.NewRenderInput("rotini", fixtureSpec())
	for _, name := range []string{"rotini.gen.tmpl", "handlers.go.tmpl"} {
		a, err := internal.Render(name, in.WithFramework("example.com/x/y", "rotini"))
		if err != nil {
			t.Fatalf("first Render(%s): %v", name, err)
		}
		b, err := internal.Render(name, in.WithFramework("example.com/x/y", "rotini"))
		if err != nil {
			t.Fatalf("second Render(%s): %v", name, err)
		}
		if string(a) != string(b) {
			t.Errorf("%s: render is non-deterministic", name)
		}
	}
}
